local H = dofile("tests/sketchybar-harness.lua")
dofile("desktop/sketchybar/items/metrics.lua")
local function sample(user, idle, time, pressure)
  H.complete("desktop-metrics", { user = user, idle = idle, system = 100, nice = 0,
    memory_percent = 92, pressure = pressure or 1, swap_gib = 11.5, monotonic = time })
end
H.emit("metrics.observer", "forced")
sample(100, 100, 10)
assert(H.items["widgets.cpu.label"].props.label.string == "—")
assert(H.items["widgets.memory.label"].props.label.string:sub(1, 1) == "~")
H.run_timer(1)
sample(150, 150, 11, 2)
assert(H.items["widgets.cpu.label"].props.label.string == "50%")
H.emit("metrics.observer", "routine")
H.complete("desktop-metrics", "failed", 1)
assert(H.items["widgets.cpu.label"].props.label.string == "—")
H.emit("metrics.observer", "routine")
sample(200, 300, 15, 4)
assert(H.items["widgets.cpu.label"].props.label.string == "—", "Failure invalidates CPU baseline")
H.emit("metrics.observer", "system_woke")
sample(2^32 - 10, 2^32 - 10, 20)
H.emit("metrics.observer", "routine")
sample(10, 10, 21)
assert(H.items["widgets.cpu.label"].props.label.string == "50%")
dofile("desktop/sketchybar/items/volume.lua")
H.emit("widgets.volume", "forced")
H.emit("widgets.volume", "volume_change", { INFO = "37" })
H.complete("desktop-audio", { device = 1, volume = 10, muted = false })
assert(H.items["widgets.volume"].props.label.string == "—", "Old device read must not overwrite event")
H.complete("desktop-audio", { device = 1, volume = 38, muted = true })
assert(H.items["widgets.volume"].props.label.string == "消音", "Mute is distinct from stored volume")
H.emit("widgets.volume", "volume_change")
H.complete("desktop-audio", { device = 2 })
assert(H.items["widgets.volume"].props.label.string == "—", "Unreadable output is not an external-device claim")
H.emit("widgets.volume", "routine")
H.complete("desktop-audio", {}, 124)
assert(H.items["widgets.volume"].props.label.string == "—")
dofile("desktop/sketchybar/items/wifi.lua")
local function network(interface, rx, tx, time)
  H.complete("desktop-network", { status = "interface", interface = interface,
    address = "192.0.2.1", gateway = "192.0.2.254", rx_bytes = rx, tx_bytes = tx, monotonic = time })
end
H.emit("widgets.wifi", "forced")
network("en7", 100, 200, 10)
H.emit("widgets.wifi", "routine")
network("en7", 1124, 2248, 20)
assert(H.items["widgets.wifi"].props.label.string:find("102B/s", 1, true))
H.emit("widgets.wifi", "routine")
network("en7", 1, 2, 30)
assert(H.items["widgets.wifi"].props.label.string == "計測中")
H.emit("widgets.wifi", "network_change")
network("utun4", nil, nil, 40)
assert(H.items["widgets.wifi"].props.label.string == "—")
assert(H.items["widgets.wifi.interface"] == nil, "Network details must not add SketchyBar popup rows")
H.emit("widgets.wifi", "network_change")
H.complete("desktop-network", { status = "no-route" })
assert(H.items["widgets.wifi"].props.label.string == "経路なし")
assert(H.items["widgets.wifi.address"] == nil)
dofile("desktop/sketchybar/items/media.lua")
local cover = H.items["widgets.media"]
local function track(name, rate)
  H.emit("media.observer", "routine")
  H.complete("nowplaying-cli", { title = name, artist = "Artist", playbackRate = rate or 1 })
end
track('Title "quoted" \\ 日本語')
assert(cover.props.width == 28 and cover.props.drawing)
assert(H.items["widgets.media.title"] == nil, "No custom media popup")
local animations = H.animations
track("Second")
assert(H.animations == animations, "Track changes cannot shift bar controls")
track("Paused", 0)
assert(cover.props.drawing, "A verified paused track remains available for resume")
H.emit("media.observer", "media_change")
assert(not cover.props.drawing, "Unverified event must clear old track immediately")
H.complete("nowplaying-cli", {})
assert(not cover.props.drawing)
sbar.add("item", "aerospace.observer", {})
dofile("desktop/sketchybar/items/battery.lua")
H.emit("widgets.battery", "forced")
H.complete("pmset -g batt", "Now drawing from 'Battery Power'\n -InternalBattery-0 75%; discharging; 3:00 remaining")
assert(H.items["widgets.battery"].props.label.string == "75%")
assert(H.items["metrics.observer"].props.update_freq == 15)
H.emit("widgets.battery", "power_source_change")
H.complete("pmset -g batt", "Now drawing from 'AC Power'\n -InternalBattery-0 80%; not charging;")
assert(H.items["widgets.battery"].props.icon.string == icons.battery.plug, "AC does not imply charging")
H.emit("widgets.battery", "routine")
H.complete("pmset -g batt", "unavailable", 1)
assert(H.items["widgets.battery"].props.label.string == "—")
print("SketchyBar widgets: verified mute, interval samples, network changes, media and battery states passed")

for _, item in ipairs(H.items) do
  assert(not tostring(item.props.position):match("^popup"), "Use native AppKit menus instead of SketchyBar popup windows")
end
assert(H.items["widgets.cpu.graph"].props.position == "right" and H.items["widgets.cpu.graph"].props.drawing)
assert(H.items["widgets.memory.graph"].props.position == "right" and H.items["widgets.memory.graph"].props.drawing)
H.emit("widgets.cpu.graph", "mouse.clicked")
local command = H.complete("native-menu", "")
assert(command:find("'cpu'", 1, true) and command:find("50%", 1, true))
H.emit("widgets.memory.graph", "mouse.clicked")
command = H.complete("native-menu", "")
assert(command:find("メモリプレッシャー", 1, true) and command:find("11.50 GiB", 1, true))
H.emit("widgets.volume", "mouse.clicked")
command = H.complete("native-menu", "")
assert(command:find("現在の値を取得できません", 1, true) and not command:find("38%", 1, true),
  "Unavailable data must not expose the last successful value in a menu")
H.emit("widgets.wifi", "mouse.clicked")
command = H.complete("native-menu", "")
assert(command:find("既定のネットワーク経路がありません", 1, true) and not command:find("192.0.2.1", 1, true))
H.emit("widgets.battery", "mouse.clicked")
assert(H.complete("native-menu", ""):find("現在の値を取得できません", 1, true))
print("SketchyBar menus: graph click targets, metric details and stale-data clearing passed")
