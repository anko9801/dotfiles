local H = dofile("tests/sketchybar-harness.lua")
local menu = require("helpers.menu")
menu.start()
menu.start()
H.complete("native-menu", "")
assert(#H.pending == 0, "Prepare one native host for the bar lifetime")
local item = sbar.add("item", "test.menu", {})
menu.bind({ item }, "cpu", function() return { "CPU", "使用率 25%" } end)
H.emit(item.name, "mouse.clicked")
local command = H.complete("menu-client", "")
assert(command:find("pub.anko.sketchybar-menu.321.987", 1, true))
assert(#H.pending == 0, "Normal clicks must not launch an AppKit process")
H.emit(item.name, "mouse.clicked")
H.complete("menu-client", "", 69)
assert(H.count_timers(0.1) == 1)
H.emit(item.name, "mouse.clicked")
H.complete("menu-client", "")
H.run_timer(0.1)
assert(#H.pending == 0, "An old click must not reappear after a newer click")
H.emit(item.name, "mouse.clicked")
H.complete("menu-client", "", 70)
assert(#H.timers == 0, "An ambiguous timeout must never duplicate a menu")
print("SketchyBar menus: one prepared host, direct click path and bounded recovery passed")
